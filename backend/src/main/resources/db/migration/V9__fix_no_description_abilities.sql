-- ========================================
-- ALIGN REMAINING ABILITY IDS
-- ========================================
-- Preserve the original order while removing the gaps left by deleted rows.
CREATE TEMP TABLE "ability_id_map" ON COMMIT DROP AS
SELECT
    "id" AS "old_id",
    ROW_NUMBER() OVER (ORDER BY "id")::bigint AS "new_id"
FROM "abilities";


-- The foreign keys are temporarily removed so parent IDs can be renumbered
-- without violating the existing non-deferrable constraints.
ALTER TABLE "pokedex"
DROP CONSTRAINT IF EXISTS "pokedex_ability_1_id_fkey";
ALTER TABLE "pokedex"
DROP CONSTRAINT IF EXISTS "pokedex_ability_2_id_fkey";
ALTER TABLE "pokedex"
DROP CONSTRAINT IF EXISTS "pokedex_hidden_ability_id_fkey";
ALTER TABLE "pokemon"
DROP CONSTRAINT IF EXISTS "pokemon_ability_id_fkey";


-- Update every reference before changing the primary keys.
UPDATE "pokedex" AS p
SET "ability_1_id" = m."new_id"
FROM "ability_id_map" AS m
WHERE p."ability_1_id" = m."old_id";

UPDATE "pokedex" AS p
SET "ability_2_id" = m."new_id"
FROM "ability_id_map" AS m
WHERE p."ability_2_id" = m."old_id";

UPDATE "pokedex" AS p
SET "hidden_ability_id" = m."new_id"
FROM "ability_id_map" AS m
WHERE p."hidden_ability_id" = m."old_id";

UPDATE "pokemon" AS p
SET "ability_id" = m."new_id"
FROM "ability_id_map" AS m
WHERE p."ability_id" = m."old_id";


-- Use a temporary range to avoid collisions while IDs are compacted.
UPDATE "abilities"
SET "id" = "id" + 1000000;

UPDATE "abilities" AS a
SET "id" = m."new_id"
FROM "ability_id_map" AS m
WHERE a."id" = m."old_id" + 1000000;


-- Restore the foreign keys with their original behaviour.
ALTER TABLE "pokedex"
ADD CONSTRAINT "pokedex_ability_1_id_fkey"
FOREIGN KEY ("ability_1_id") REFERENCES "abilities"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE "pokedex"
ADD CONSTRAINT "pokedex_ability_2_id_fkey"
FOREIGN KEY ("ability_2_id") REFERENCES "abilities"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE "pokedex"
ADD CONSTRAINT "pokedex_hidden_ability_id_fkey"
FOREIGN KEY ("hidden_ability_id") REFERENCES "abilities"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE "pokemon"
ADD CONSTRAINT "pokemon_ability_id_fkey"
FOREIGN KEY ("ability_id") REFERENCES "abilities"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;


-- Keep future generated IDs aligned with the compacted table.
SELECT setval(
    pg_get_serial_sequence('"abilities"', 'id'),
    COALESCE(MAX("id"), 1),
    MAX("id") IS NOT NULL
)
FROM "abilities";
